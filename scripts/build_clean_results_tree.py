"""Assemble a single flat results tree: one folder per model, plus summaries.

Builds into ka59_game/results_clean/ and copies rather than moves, so the
existing layout -- which the audit reads by explicit path -- keeps working
until someone decides to delete it.

    results_clean/
      gpt-5.2/                          every GPT-5.2 trial, any effort
      deepseek-v4-pro/                  every DeepSeek trial, any effort
      ablation_summary_gpt_5_2.json
      ablation_summary_deepseek_v4_pro.json

Makes no model calls.
"""

from __future__ import annotations

import json
import shutil
from pathlib import Path
from typing import Any

from scripts.audit_ka59_camera_ready import REPO_ROOT
from scripts.build_camera_ready_ablation_summaries import build_summary

DEST = REPO_ROOT / "ka59_game" / "results_clean"
SOURCES: dict[str, tuple[str, ...]] = {
    "gpt-5.2": (
        "ka59_game/results/gpt-5.2/run_*.json",
        "ka59_game/results/gpt-5.2-recovered/*.json",
        "ka59_game/results/camera_ready/gpt-5.2-*/*.json",
    ),
    "deepseek-v4-pro": (
        "ka59_game/results/deepseek-v4-pro/run_*.json",
        "ka59_game/results/deepseek-v4-pro-medium/*.json",
        "ka59_game/results/camera_ready/deepseek-v4-pro-*/*.json",
    ),
}
SUMMARY_STEM = {"openai/gpt-5.2": "gpt_5_2", "deepseek-v4-pro": "deepseek_v4_pro"}
MODEL_DIR = {"openai/gpt-5.2": "gpt-5.2", "deepseek-v4-pro": "deepseek-v4-pro"}


def copy_trials(counts: dict[str, int] | None = None) -> dict[str, str]:
    """Copy every trial into its model folder. Returns basename -> new path."""
    counts = counts if counts is not None else {}
    index: dict[str, str] = {}
    for model_dir, globs in SOURCES.items():
        target = DEST / model_dir
        target.mkdir(parents=True, exist_ok=True)
        seen: set[str] = set()
        for pattern in globs:
            for source in sorted(REPO_ROOT.glob(pattern)):
                if source.name in seen:
                    continue           # same trial reached by two globs
                seen.add(source.name)
                shutil.copy2(source, target / source.name)
                index[source.name] = str(
                    (target / source.name).relative_to(REPO_ROOT)
                )
        print(f"  {model_dir:18s} {len(seen):4d} trials")
        counts[model_dir] = len(seen)
    return index


def _remap(paths: list[str], index: dict[str, str]) -> list[str]:
    return [index.get(Path(p).name, p) for p in paths]


def write_summaries(index: dict[str, str]) -> None:
    for model, stem in SUMMARY_STEM.items():
        rows: list[dict[str, Any]] = build_summary(model)
        for row in rows:
            for key in ("run_files", "accepted_run_files", "camera_ready_run_files",
                        "pooled_from_format_only_fallthrough",
                        "excluded_infrastructure_files"):
                if key in row:
                    row[key] = _remap(row[key], index)
        path = DEST / f"ablation_summary_{stem}.json"
        path.write_text(json.dumps(rows, indent=2) + "\n")
        print(f"  wrote {path.relative_to(REPO_ROOT)}")


README = """# KA59-Simple results

One folder per model, holding every trial for that model at any reasoning
effort, plus the ablation summary for each. Generated by
`python -m scripts.build_clean_results_tree` (no model calls); the whole tree is
rebuilt each run, so edit the generator rather than the files.

{table}

Effort and condition are not encoded in the folder name. Read them from each
trial's `reasoning_effort` and `config` fields, or from the `run_files` lists in
the summaries, which group trials by cell.

`ablation_summary_*.json` follows the schema of
`bp35/results/ablation_summary_*.json`, with two differences: the KA59-Simple
metric set replaces bp35's gravity/undo counters, and audit fields are appended
after `run_files` (`denominator`, `additional_trials_needed`, the provenance
splits, and `excluded_infrastructure_files`).

`n_trials` is the audited `infrastructure_clean_scored` denominator, not a
nominal trial count: provider and environment failures are excluded rather than
scored as losses. That is the correction the camera-ready audit exists to make.

## Provenance

This tree is a **copy**. The sources remain in place and are still what the
audit and the runner read:

- `ka59_game/results/{{gpt-5.2,deepseek-v4-pro,deepseek-v4-pro-medium}}/` --
  accepted historical trials, referenced by path from the historical
  `ablation_summary_*.json`.
- `ka59_game/results/gpt-5.2-recovered/` -- 20 trials rebuilt from surviving git
  blobs after commit c9063f29 became unreachable; each verified against the
  digest recorded when it was last readable.
- `camera_ready/results/<protocol_id>/` -- trials written by
  `scripts/run_ka59_camera_ready.py`, resolved by identity hash. The runner
  reads and writes there, so those directories cannot be moved without breaking
  `--resume`.

Deleting the sources would break the audit and the runner. Retire them
deliberately, not as tidy-up.
"""


def write_readme(counts: dict[str, int]) -> None:
    table = "\n".join(
        ["| Folder | Trials |", "|---|---:|"]
        + [f"| `{name}/` | {n} |" for name, n in sorted(counts.items())]
    )
    (DEST / "README.md").write_text(README.format(table=table))


def main() -> int:
    if DEST.exists():
        shutil.rmtree(DEST)
    DEST.mkdir(parents=True)
    counts: dict[str, int] = {}
    index = copy_trials(counts)
    write_summaries(index)
    write_readme(counts)
    missing = [
        relative
        for stem in SUMMARY_STEM.values()
        for row in json.loads((DEST / f"ablation_summary_{stem}.json").read_text())
        for relative in row["run_files"]
        if not (REPO_ROOT / relative).exists()
    ]
    print(f"  summary run_files pointing outside the tree: {len(missing)}")
    return 1 if missing else 0


if __name__ == "__main__":
    raise SystemExit(main())
